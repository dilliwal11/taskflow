-- V2: outbox table for emails.
-- Services insert a row here in the SAME transaction as the business change,
-- and a background job sends them later. If the transaction rolls back, no email goes out.

create table notifications (
    id         bigint generated by default as identity primary key,
    recipient  varchar(255)  not null,
    subject    varchar(200)  not null,
    body       varchar(2000) not null,
    status     varchar(20)   not null default 'PENDING',
    attempts   integer       not null default 0,
    last_error varchar(500),
    created_at timestamptz   not null default now(),
    sent_at    timestamptz,
    constraint ck_notifications_status check (status in ('PENDING', 'SENT', 'FAILED'))
);

-- Partial index: the dispatcher only ever looks for PENDING rows,
-- so the index stays tiny even when the table holds millions of SENT rows.
create index ix_notifications_pending on notifications (created_at) where status = 'PENDING';
