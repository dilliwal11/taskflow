-- V1: users, teams, memberships, projects and tasks.
-- Flyway runs each V<n>__*.sql file exactly once, in order, and records it in flyway_schema_history.
-- Never edit a migration that has already run somewhere: add a new one instead.

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null,
    password_hash varchar(255) not null,
    display_name  varchar(100) not null,
    created_at    timestamptz  not null default now(),
    constraint uq_users_email unique (email)
);

create table teams (
    id         bigint generated by default as identity primary key,
    name       varchar(100) not null,
    created_at timestamptz  not null default now()
);

-- Join table for the many-to-many between users and teams, carrying the role.
create table team_members (
    id        bigint generated by default as identity primary key,
    team_id   bigint      not null references teams (id) on delete cascade,
    user_id   bigint      not null references users (id) on delete cascade,
    role      varchar(20) not null,
    joined_at timestamptz not null default now(),
    constraint uq_team_members_team_user unique (team_id, user_id),
    constraint ck_team_members_role check (role in ('OWNER', 'MEMBER'))
);

-- The unique constraint above already indexes (team_id, user_id).
-- "Which teams is this user in?" filters by user_id alone, so it needs its own index.
create index ix_team_members_user on team_members (user_id);

create table projects (
    id          bigint generated by default as identity primary key,
    team_id     bigint        not null references teams (id) on delete cascade,
    name        varchar(120)  not null,
    description varchar(2000),
    created_at  timestamptz   not null default now()
);

create index ix_projects_team on projects (team_id);

create table tasks (
    id          bigint generated by default as identity primary key,
    project_id  bigint        not null references projects (id) on delete cascade,
    title       varchar(200)  not null,
    description varchar(2000),
    status      varchar(20)   not null default 'TODO',
    priority    varchar(20)   not null default 'MEDIUM',
    assignee_id bigint        references users (id) on delete set null,
    created_by  bigint        not null references users (id),
    due_date    date,
    created_at  timestamptz   not null default now(),
    updated_at  timestamptz   not null default now(),
    -- Optimistic locking counter, managed by JPA's @Version.
    version     integer       not null default 0,
    constraint ck_tasks_status check (status in ('TODO', 'IN_PROGRESS', 'DONE')),
    constraint ck_tasks_priority check (priority in ('LOW', 'MEDIUM', 'HIGH'))
);

-- The board query is "tasks of a project, optionally by status": a composite index covers both.
create index ix_tasks_project_status on tasks (project_id, status);
create index ix_tasks_assignee on tasks (assignee_id);
